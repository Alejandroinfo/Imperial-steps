'use strict';
// 17 historias más de 4 capítulos (con las 3 de js/motor/historias.js suman 20). Mismo formato y mismas reglas:
// el capítulo 1 llega hacia el paso 10 y los demás cada 8; lo que eliges en cada capítulo cambia el siguiente y el final;
// SIEMPRE son oportunidades: «dejarlo pasar» no cuesta nada ni castiga. Los montos que se escriben aquí son los básicos:
// en la partida se escalan con el paso (como los encuentros).
//
// Cada historia tiene dos «marcas» (por ejemplo M y P). Los capítulos 2 y 3 tienen una variante por marca, con una opción
// que sigue el camino y otra que cambia de camino; el capítulo 4 depende de la marca que más elegiste.
// ganancias posibles: units, res+n, prog, eq, rel, tpob, saber, bld, tres  (ver js/motor/encuentros.js)

// o(marca, texto, [recurso, monto] o null, ganancia)
const _o = (t, lbl, c, gain) => ({ t, lbl, cost: c ? { res: c[0], n: c[1] } : null, gain });
// una historia a partir de sus piezas: c2 y c3 = [[texto, [opción, opción]] para la 1.ª marca, [...] para la 2.ª]
// t4 = [final de la 1.ª marca, final de la 2.ª]; o4 = [[texto, costo, ganancia 1.ª, ganancia 2.ª], ...] (2 opciones)
function _story(n, tags, t1, o1, c2, c3, t4, o4) {
  const nd = x => x.replace(/\.$/, '');   // la interfaz agrega el punto final
  const [a, b] = tags, pick = c => ({ [a]: { txt: nd(c[0][0]), opts: c[0][1] }, [b]: { txt: nd(c[1][0]), opts: c[1][1] } });
  return {
    n, tags, 1: { txt: nd(t1), opts: o1 }, 2: pick(c2), 3: pick(c3),
    4: { txt: { [a]: nd(t4[0]), [b]: nd(t4[1]) },
         opts: o4.map(x => ({ lbl: x[0], cost: x[1] ? { res: x[1][0], n: x[1][1] } : null, g: { [a]: x[2], [b]: x[3] } })) }
  };
}

